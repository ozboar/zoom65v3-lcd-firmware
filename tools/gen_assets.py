#!/usr/bin/env python3
"""Generate src/assets.c and src/assets.h from the art and fonts.

Images are stored palette and RLE encoded in LCD stream order, which is screen x
descending and y ascending for each column. Fonts are stored as 2 bits per pixel.

usage: gen_assets.py <bongo frames dir> <fonts dir> <output dir>
"""
import json
import re
import struct
import sys
from pathlib import Path

from PIL import Image

FRAMES, FONTS, OUT = map(Path, sys.argv[1:4])
DIGIT_SCALE = 3
IMAGES = ("bongo_base", "bongo_left_up", "bongo_left_down", "bongo_right_up", "bongo_right_down", "bongo_eye_right", "bongo_eye_left")


def rgb565(rgb):
    r, g, b = rgb[:3]
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def encode_image(path):
    image = Image.open(path).convert("RGB")
    width, height = image.size
    palette, stream = [], []
    for x in reversed(range(width)):
        for y in range(height):
            color = rgb565(image.getpixel((x, y)))
            if color not in palette:
                palette.append(color)
            stream.append(palette.index(color))
    if len(palette) > 256:
        sys.exit(f"{path}: too many colors")

    rle = bytearray()
    i = 0
    while i < len(stream):
        run = 1
        while i + run < len(stream) and stream[i + run] == stream[i] and run < 255:
            run += 1
        rle += bytes((run, stream[i]))
        i += run
    return width, height, palette, bytes(rle)


def read_c_array(path):
    text = path.read_text()
    body = text[text.index("{", text.index("const uint8_t")) :]
    return bytes(int(v, 16) for v in re.findall(r"0x([0-9A-Fa-f]{2})", body))


def parse_qff(data):
    """Returns (line height, bits per pixel, {char: (width, pixel levels 0-3)})."""
    pos = 0
    line_height = fmt = table = blob = palette = None
    while pos < len(data):
        block, neg, length = data[pos], data[pos + 1], int.from_bytes(data[pos + 2 : pos + 5], "little")
        if block != (~neg & 0xFF):
            sys.exit(f"bad QFF block at {pos}")
        body = data[pos + 5 : pos + 5 + length]
        if block == 0x00:
            line_height, fmt, compression = body[12], body[16], body[18]
            if compression != 0:
                sys.exit("compressed QFF fonts are not supported")
        elif block == 0x01:
            table = [int.from_bytes(body[i * 3 : i * 3 + 3], "little") for i in range(95)]
        elif block == 0x03:
            palette = [body[i * 3 + 2] for i in range(length // 3)]
        elif block == 0x04:
            blob = body
        pos += 5 + length

    bpp = {0: 1, 1: 2, 2: 4, 3: 8, 4: 1, 5: 2, 6: 4, 7: 8}[fmt]
    glyphs = {}
    for index, entry in enumerate(table):
        width = entry & 0x3F
        offset = entry >> 6
        levels = []
        for p in range(width * line_height):
            bit = p * bpp
            raw = (blob[offset + bit // 8] >> (bit % 8)) & ((1 << bpp) - 1)
            value = palette[raw] if palette else raw * 255 // ((1 << bpp) - 1)
            levels.append(round(value * 3 / 255))
        glyphs[0x20 + index] = (width, levels)
    return line_height, glyphs


def scale_digits(height, glyphs):
    """The small font's digits at a whole number scale, so they stay sharp and match it."""
    width = max(glyphs[code][0] for code in range(0x30, 0x3A))
    rows = [y for y in range(height) if any(glyphs[code][1][y * glyphs[code][0] + x] for code in range(0x30, 0x3A) for x in range(glyphs[code][0]))]
    scaled = {}
    for code in range(0x30, 0x3A):
        glyph_width, levels = glyphs[code]
        left = (width - glyph_width) // 2
        pixels = []
        for y in rows:
            line = [0] * left + levels[y * glyph_width : (y + 1) * glyph_width] + [0] * (width - glyph_width - left)
            for _ in range(DIGIT_SCALE):
                pixels += [level for level in line for _ in range(DIGIT_SCALE)]
        scaled[code] = (width * DIGIT_SCALE, pixels)
    return len(rows) * DIGIT_SCALE, scaled


def encode_font(height, glyphs, first, last):
    widths, offsets, blob = [], [], bytearray()
    for code in range(first, last + 1):
        width, levels = glyphs[code]
        widths.append(width)
        offsets.append(len(blob))
        packed = bytearray((len(levels) + 3) // 4)
        for i, level in enumerate(levels):
            packed[i // 4] |= level << ((i % 4) * 2)
        blob += packed
    return height, widths, offsets, bytes(blob)


def c_bytes(data):
    lines = []
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in data[i : i + 16]) + ",")
    return "\n".join(lines)


c = ['// Generated by tools/gen_assets.py', '#include "assets.h"', ""]
h = ['// Generated by tools/gen_assets.py', "#pragma once", "", '#include "draw.h"', ""]
total = 0

for name in IMAGES:
    width, height, palette, rle = encode_image(FRAMES / f"{name}.png")
    total += len(rle) + len(palette) * 2
    print(f"{name}: {width}x{height}, {len(palette)} colors, {len(rle)} bytes")
    c.append(f"static const uint16_t {name}_palette[] = {{{', '.join(f'0x{v:04X}' for v in palette)}}};")
    c.append(f"static const uint8_t {name}_rle[] = {{\n{c_bytes(rle)}\n}};")
    c.append(f"const image_t {name} = {{{width}, {height}, {name}_palette, {name}_rle, sizeof({name}_rle)}};")
    c.append("")
    h.append(f"extern const image_t {name};")

small_height, small_glyphs = parse_qff(read_c_array(FONTS / "thintel15.qff.c"))
digit_height, digit_glyphs = scale_digits(small_height, small_glyphs)
for name, font_height, glyphs, first, last in (
    ("font_small", small_height, small_glyphs, 0x20, 0x7E),
    ("font_digits", digit_height, digit_glyphs, 0x30, 0x39),
):
    height, widths, offsets, blob = encode_font(font_height, glyphs, first, last)
    total += len(blob) + len(widths) * 3
    print(f"{name}: height {height}, {last - first + 1} glyphs, {len(blob)} bytes, widths {min(widths)}-{max(widths)}")
    c.append(f"static const uint8_t {name}_widths[] = {{{', '.join(map(str, widths))}}};")
    c.append(f"static const uint16_t {name}_offsets[] = {{{', '.join(map(str, offsets))}}};")
    c.append(f"static const uint8_t {name}_data[] = {{\n{c_bytes(blob)}\n}};")
    c.append(f"const font_t {name} = {{{height}, 0x{first:02X}, 0x{last:02X}, {name}_widths, {name}_offsets, {name}_data}};")
    c.append("")
    h.append(f"extern const font_t {name};")

cat = json.loads((FRAMES / "cat_keys.json").read_text())
offsets, runs = [], bytearray()
for row in range(5):
    for col in range(16):
        offsets.append(len(runs) // 3)
        for x, y, length in cat["keys"].get(f"{row},{col}", []):
            runs += bytes((x, y, length))
offsets.append(len(runs) // 3)
c.append(f"const uint16_t cat_key_offsets[] = {{{', '.join(map(str, offsets))}}};")
c.append(f"const uint8_t cat_key_runs[] = {{\n{c_bytes(runs)}\n}};")
h.append("")
h.append("/* Pixels of each key on the cat's keyboard, as x, y and length of vertical runs */")
h.append("extern const uint16_t cat_key_offsets[];")
h.append("extern const uint8_t cat_key_runs[];")
total += len(runs) + len(offsets) * 2
for key in ("left_up", "left_down", "right_up", "right_down"):
    name = f"cat_mask_{key}"
    box, bits = cat[key]["box"], cat[key]["bits"]
    width = box[2] - box[0]
    packed = bytearray((width * len(bits) + 7) // 8)
    for y, line in enumerate(bits):
        for x, visible in enumerate(line):
            if visible:
                packed[(y * width + x) // 8] |= 1 << ((y * width + x) % 8)
    c.append(f"const uint8_t {name}[] = {{\n{c_bytes(packed)}\n}};")
    h.append(f"/* Set where this paw pose does not cover the keyboard, {width} bits per row */")
    h.append(f"extern const uint8_t {name}[];")
    total += len(packed)
print(f"cat keys: {len(runs) // 3} runs")

(OUT / "assets.c").write_text("\n".join(c) + "\n")
(OUT / "assets.h").write_text("\n".join(h) + "\n")
print(f"total {total} bytes")
