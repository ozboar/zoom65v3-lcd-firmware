#!/usr/bin/env python3
"""Write the firmware and first stage loader as a C file for the keyboard.

usage: export_qmk.py <firmware.bin> <stage1.bin> <lcd_image.c>
"""
import hashlib
import sys
import zlib
from pathlib import Path


def load(path):
    image = Path(path).read_bytes()
    return image + b"\xff" * (-len(image) % 4)


def array(name, image):
    rows = [", ".join(f"0x{b:02X}" for b in image[i : i + 16]) for i in range(0, len(image), 16)]
    body = "\n".join(f"    {row}," for row in rows)
    return f"const uint32_t {name}_size = {len(image)};\n\nconst uint8_t {name}[] = {{\n{body}\n}};\n"


firmware = load(sys.argv[1])
stage1 = load(sys.argv[2])
Path(sys.argv[3]).write_text(
    f"""// Generated by zoom65v3-lcd-firmware tools/export_qmk.py
// firmware sha256 {hashlib.sha256(firmware).hexdigest()}
#include <stdint.h>

const uint32_t lcd_image_crc = 0x{zlib.crc32(firmware):08X};

{array("lcd_image", firmware)}
{array("lcd_stage1", stage1)}"""
)
print(f"wrote {sys.argv[3]}, firmware {len(firmware)} bytes, first stage {len(stage1)} bytes")
